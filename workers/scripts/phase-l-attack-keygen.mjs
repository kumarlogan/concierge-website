// ┌─────────────────────────────────────────────────────────────┐
// │ Phase L — Attack key generation (LOCAL ONLY, NOT COMMITTED)   │
// │ Generates an RS256 keypair used ONLY to mint synthetic        │
// │ Patient A / Patient B JWTs for the local end-to-end IDOR     │
// │ attack harness. Writes the public key into .dev.vars so the   │
// │ real worker (Miniflare) verifies real signatures, and emits   │
// │ a bundled migrations module (tests/.phase-l-migrations.ts) so │
// │ the attack test can apply the schema to the pool's own D1     │
// │ database (the pool uses a different D1 location than the      │
// │ globalSetup CLI apply, hence must self-provision). No prod    │
// │ key or schema is touched.                                     │
// └─────────────────────────────────────────────────────────────┘
import { webcrypto as crypto } from "node:crypto";
import { writeFileSync, readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = fileURLToPath(new URL(".", import.meta.url));
const workersDir = join(__dirname, "..");
const migrationsDir = join(workersDir, "migrations");

const KID = "phase-l-attack-kid";

function pemExport(kind, der) {
  const b64 = Buffer.from(der).toString("base64");
  const lines = b64.match(/.{1,64}/g).join("\n");
  const label = kind === "public" ? "PUBLIC KEY" : "PRIVATE KEY";
  return `-----BEGIN ${label}-----\n${lines}\n-----END ${label}-----`;
}

const keyPair = await crypto.subtle.generateKey(
  { name: "RSASSA-PKCS1-v1_5", modulusLength: 2048, publicExponent: new Uint8Array([1, 0, 1]), hash: "SHA-256" },
  true,
  ["sign", "verify"],
);

const publicDer = await crypto.subtle.exportKey("spki", keyPair.publicKey);
const privateDer = await crypto.subtle.exportKey("pkcs8", keyPair.privateKey);
const publicPem = pemExport("public", publicDer);
const privatePem = pemExport("private", privateDer);

// .dev.vars is gitignored — the Miniflare worker reads JWT vars from here.
const devVars = [
  `JWT_PRIVATE_KEY='${privatePem}'`,
  `JWT_PUBLIC_KEY='${publicPem}'`,
  `JWT_KID='${KID}'`,
  `PLATFORM_JWT_PUBLIC_KEY='${publicPem}'`,
  `PLATFORM_JWT_KID='${KID}'`,
  `ENVIRONMENT='test'`,
  ``,
].join("\n");
writeFileSync(join(workersDir, ".dev.vars"), devVars);

// Concatenate all migration SQL (order by filename), strip comments/blank lines,
// emit as a TS module the test can import inside the workerd sandbox.
const files = readdirSync(migrationsDir)
  .filter((f) => f.endsWith(".sql"))
  .sort();
const combined = files
  .map((f) => readFileSync(join(migrationsDir, f), "utf8"))
  .join("\n")
  .split("\n")
  .map((line) => line.replace(/--.*$/, "")) // strip SQL line comments
  .join("\n")
  .replace(/\s+/g, " ") // collapse whitespace for a compact literal
  .trim();
writeFileSync(
  join(workersDir, "tests", ".phase-l-migrations.ts"),
  `// AUTO-GENERATED by scripts/phase-l-attack-keygen.mjs — do NOT edit.\n` +
    `// Concatenated D1 migration SQL for the Phase L attack test pool.\n` +
    `export const MIGRATION_SQL = ${JSON.stringify(combined)};\n`,
);

console.log("Phase L attack harness written:");
console.log("  .dev.vars                     (gitignored) JWT vars for worker");
console.log("  tests/.phase-l-migrations.ts (gitignored) schema SQL for pool D1");
console.log("KID =", KID, "| migrations:", files.length);
